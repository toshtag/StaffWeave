-- その日を出勤日として数えるかどうかを、計算の結果として残す。
--
-- 勤務区分は `counts_as_working_day` を持つが、どこからも読まれていなかった。
-- 出勤日数は「実労働が 0 分より多い日」を数えて出しており、区分の設定は
-- 結果に現れない。設定できるのに効かない値は、設定した人を誤らせる。
--
-- 数える側で勤務区分を辿り直すことはしない。月次と給与は保存済みの日次から
-- 組み立てる。あとから区分を直したときに、締めた月の日数だけが動く。
-- その日の計算と一緒に固めれば、締めた値は締めた時点のまま残る。
--
-- 既定は true。勤務区分を持たない日は、これまでどおり実労働があれば数える。
ALTER TABLE attendance_calculations
  ADD COLUMN counts_as_working_day boolean NOT NULL DEFAULT true;
