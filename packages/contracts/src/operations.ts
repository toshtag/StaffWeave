export type HttpMethod = 'get' | 'post' | 'patch' | 'put' | 'delete';

/** 認証方式。フェーズが進むにつれて API キーが加わる。 */
/**
 * 呼び出しに必要な資格。
 * `sessionOrApiKey` は、画面のセッションでも API キーでも呼べる経路を表す。
 */
export type SecurityRequirement = 'public' | 'session' | 'deviceSignature' | 'sessionOrApiKey';

export interface ResponseContract {
  status: number;
  description: string;
  schema?: JsonSchema;
}

export interface PathParameterContract {
  name: string;
  description: string;
  schema: JsonSchema;
}

export interface OperationContract {
  operationId: string;
  method: HttpMethod;
  /** OpenAPI 形式のパス（`/employees/{employeeId}`）。 */
  path: string;
  summary: string;
  tags: readonly string[];
  security: SecurityRequirement;
  pathParameters?: readonly PathParameterContract[];
  requestBody?: JsonSchema;
  /** 要求本文の内容種別。省略すると application/json。 */
  requestContentType?: string;
  /** 応答本文の内容種別。省略すると application/json。 */
  responseContentType?: string;
  query?: JsonSchema;
  responses: readonly ResponseContract[];
}

const unauthorized: ResponseContract = {
  status: 401,
  description: '認証されていない',
  schema: errorResponseSchema,
};
