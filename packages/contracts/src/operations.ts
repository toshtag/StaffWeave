const invalidRequest: ResponseContract = {
  status: 400,
  description: '要求の内容が契約に合わない',
  schema: errorResponseSchema,
};
const conflict: ResponseContract = {
  status: 409,
  description: '既存のデータと衝突している',
  schema: errorResponseSchema,
};

